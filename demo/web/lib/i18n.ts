const WORDS: Record<Lang, Words> = { en, it };

/** The words of a language, and what is written with them: a day, a number, a time ago. */
function text(lang: Lang) {
  const w = WORDS[lang];
  const dayFormat = new Intl.DateTimeFormat(w.locale, {
    weekday: "short",
    day: "numeric",
    month: "short",
    timeZone: "Europe/Rome",
  });
  return {
    ...w,
    lang,
    day: (date: string) => dayFormat.format(new Date(`${date}T12:00:00Z`)),
    whole: (value: number) => Math.round(value).toLocaleString(w.locale),
    mm: (value: number | null | undefined) =>
      value === null || value === undefined
        ? "–"
        : value.toLocaleString(w.locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 }),
    ago(stamp: string, now = Date.now()): string {
      const minutes = Math.max(0, Math.round((now - when(stamp).getTime()) / 60000));
      if (minutes < 1) return w.justNow;
      if (minutes < 60) return w.minAgo(minutes);
      return w.hoursAgo(Math.floor(minutes / 60), minutes % 60);
    },
    going(moving: Moving): string | null {
      if (!moving) return null;
      if (moving.kmh < 2) return w.almostStill;
      return w.towards(Math.round(moving.kmh), w.winds[Math.round(moving.towards_degrees / 45) % 8]);
    },
    alert: (zone: ZoneDay) => (zone.level ? w.alertOf(w.colours[zone.colour]) : w.noAlert),
    state: (on: boolean | null) => (on === null ? w.status.unknown : on ? w.status.on : w.status.off),
    source: (source: string) => w.sources[source] ?? source,
  };
}

export type Text = ReturnType<typeof text>;
export const TEXT: Record<Lang, Text> = { en: text("en"), it: text("it") };

export const LangContext = createContext<Text>(TEXT.en);
export const useText = () => useContext(LangContext);
